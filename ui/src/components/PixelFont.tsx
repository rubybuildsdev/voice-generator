export type MosaicIconName = keyof typeof ICONS
export type PixelGlyph = { x: number; w: number; cells: number[][] }

export function layoutPixels(text: string) {
  const glyphs: PixelGlyph[] = []
  let x = 0
  for (const ch of text) {
    const g = GLYPHS[ch] || GLYPHS[ch.toUpperCase()]
    if (!g) {
      x += 3
      continue
    }
    const rows = g.split("/")
    const w = Math.max(...rows.map((r) => r.length))
    const cells: number[][] = []
    rows.forEach((r, y) => {
      for (let i = 0; i < r.length; i++) {
        if (r[i] === "#") cells.push([x + i, y])
      }
    })
    glyphs.push({ x, w, cells })
    x += w + 1
  }
  return { width: Math.max(1, x - 1), height: 8, glyphs }
}

export function PixelText({
  text,
  className,
  maxWidth,
}: {
  text: string
  className?: string
  maxWidth?: number
}) {
  const lay = React.useMemo(() => layoutPixels(text), [text])
  const vw = lay.width + 1
  const vh = lay.height + 1
  return (
    <svg
      className={"mpt-ptext" + (className ? " " + className : "")}
      viewBox={`-0.5 -0.5 ${vw} ${vh}`}
      aria-hidden="true"
      focusable="false"
      style={
        {
          "--w": vw,
          "--wmax": maxWidth || vw,
          aspectRatio: `${vw} / ${vh}`,
        } as React.CSSProperties
      }
    >
      {lay.glyphs.map((g, gi) => (
        <g key={gi} className="mpt-glyph">
          {g.cells.map(([cx, cy], i) => (
            <rect
              key={i}
              className="mpt-px"
              x={cx + 0.06}
              y={cy + 0.06}
              width={0.88}
              height={0.88}
              rx={0.16}
              data-x={cx + 0.06}
              data-y={cy + 0.06}
            />
          ))}
        </g>
      ))}
    </svg>
  )
}

export function PixelIcon({
  name,
  className,
}: {
  name: MosaicIconName
  className?: string
}) {
  const rows = (ICONS[name] || ICONS.spark).split("/")
  const cells: number[][] = []
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      if (r[x] === "#") cells.push([x, y])
    }
  })
  return (
    <svg
      className={"mpt-picon" + (className ? " " + className : "")}
      viewBox="0 0 7 7"
      aria-hidden="true"
      focusable="false"
    >
      {cells.map(([x, y], i) => (
        <rect key={i} x={x + 0.08} y={y + 0.08} width={0.84} height={0.84} rx={0.12} />
      ))}
    </svg>
  )
}

